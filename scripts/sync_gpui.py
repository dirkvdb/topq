#!/usr/bin/env python3
"""Sync themes and agent skills from the GPUI Kit release pinned in Cargo.lock."""

import argparse
import io
import json
import re
import shutil
import sys
import tarfile
import tempfile
import tomllib
from pathlib import Path, PurePosixPath
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ("gpui-kit", "gpui-kit-design-guides")


def download_archive(url):
    with urlopen(url, timeout=120) as response:
        return tarfile.open(fileobj=io.BytesIO(response.read()), mode="r:gz")


def read_member(archive, name):
    with archive.extractfile(name) as file:
        return file.read()


def locked_release():
    with (ROOT / "Cargo.lock").open("rb") as file:
        packages = tomllib.load(file)["package"]
    packages = [package for package in packages if package["name"] == "gpui-kit"]
    if len(packages) != 1:
        raise ValueError("Expected exactly one GPUI Kit version in Cargo.lock")
    package = packages[0]
    if package.get("source") != "registry+https://github.com/rust-lang/crates.io-index":
        raise ValueError("Expected a crates.io GPUI Kit dependency in Cargo.lock")
    version = package["version"]

    with download_archive(f"https://static.crates.io/crates/gpui-kit/gpui-kit-{version}.crate") as archive:
        metadata = json.loads(read_member(archive, f"gpui-kit-{version}/.cargo_vcs_info.json"))
    revision = metadata["git"]["sha1"]
    if not isinstance(revision, str) or not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("The published GPUI Kit crate contains an invalid source revision")
    return version, revision


def collect_themes(archive, version, revision):
    themes = {}
    directory = PurePosixPath(f"gpui-kit-{revision}/themes")
    for member in archive.getmembers():
        path = PurePosixPath(member.name)
        if not member.isfile() or path.parent != directory or path.suffix != ".json":
            continue
        if not re.fullmatch(r"[a-z0-9_-]+\.json", path.name):
            raise ValueError(f"Unsupported theme filename: {path.name}")
        content = read_member(archive, member.name)
        variants = json.loads(content.decode("utf-8")).get("themes")
        if not isinstance(variants, list) or not variants:
            raise ValueError(f"Invalid theme file: {path.name}")
        themes[path.name] = content
    if not themes:
        raise ValueError(f"GPUI Kit {version} contains no theme files")
    return themes


def collect_skills(archive, version, revision):
    files = {skill: {} for skill in SKILLS}
    directory = PurePosixPath(f"gpui-kit-{revision}/skills")
    for member in archive.getmembers():
        path = PurePosixPath(member.name)
        if not path.is_relative_to(directory):
            continue
        relative = path.relative_to(directory)
        if not relative.parts or relative.parts[0] not in SKILLS:
            continue
        if ".." in relative.parts:
            raise ValueError(f"Unsafe skill path: {member.name}")
        if member.isdir():
            continue
        if not member.isfile() or len(relative.parts) < 2:
            raise ValueError(f"Unsupported skill archive entry: {member.name}")
        skill = relative.parts[0]
        files[skill][Path(*relative.parts[1:])] = read_member(archive, member.name)
    for skill, contents in files.items():
        if Path("SKILL.md") not in contents:
            raise ValueError(f"GPUI Kit {version} contains no skills/{skill}/SKILL.md")
    return files


def sync_themes(themes, version, revision):
    embedded = (
        "// Generated by just sync-themes; do not edit.\n"
        f"// GPUI Kit {version}, source revision {revision}.\n\n"
        "pub(crate) const THEMES: &[(&str, &str)] = &[\n"
        + "".join(f'    ("{name}", include_str!("../themes/{name}")),\n' for name in sorted(themes))
        + "];\n"
    )
    destination = ROOT / "themes"
    destination.mkdir(exist_ok=True)
    for name, content in themes.items():
        (destination / name).write_bytes(content)
    for stale in destination.glob("*.json"):
        if stale.name not in themes:
            stale.unlink()
    (ROOT / "src/bundled_themes.rs").write_text(embedded, encoding="utf-8", newline="\n")
    print(f"Synced {len(themes)} theme files from gpui-kit {version} ({revision})")


def sync_skills(files, version, revision):
    destination = ROOT / ".agents/skills"
    destination.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".sync-gpui-", dir=destination) as temporary:
        staging = Path(temporary)
        for skill, contents in files.items():
            for relative, content in contents.items():
                target = staging / skill / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)
        for skill in SKILLS:
            target = destination / skill
            if target.is_symlink():
                target.unlink()
            elif target.exists():
                shutil.rmtree(target)
            (staging / skill).rename(target)
    print(f"Synced {len(SKILLS)} agent skills from gpui-kit {version} ({revision})")


def main(target):
    version, revision = locked_release()
    with download_archive(f"https://codeload.github.com/longbridge/gpui-kit/tar.gz/{revision}") as archive:
        themes = collect_themes(archive, version, revision) if target in ("themes", "all") else None
        skills = collect_skills(archive, version, revision) if target in ("skills", "all") else None
    # All downloads and validation finish before changing the checked-in files.
    if themes is not None:
        sync_themes(themes, version, revision)
    if skills is not None:
        sync_skills(skills, version, revision)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", choices=("themes", "skills", "all"), nargs="?", default="all")
    args = parser.parse_args()
    try:
        main(args.target)
    except (OSError, ValueError, KeyError, tarfile.TarError) as error:
        sys.exit(f"Could not sync GPUI Kit {args.target}: {error}")
